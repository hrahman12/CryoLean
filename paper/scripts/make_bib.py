#!/usr/bin/env python
"""Write paper/references.bib from the verified literature sweep (paper/data/research_workflow.json).

Only references that the independent verifier found to exist are written; its metadata corrections are applied."""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "paper" / "data" / "research_workflow.json"
OUT = ROOT / "paper" / "references.bib"
RENAME = {"guo2026": "li2026"}          # verifier: Lulu Guo is not first author (arXiv 2609.03621 lists Xiaobo Li first)


def esc(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def authors_bib(a: str) -> str:
    a = re.sub(r",?\s*et al\.?.*$", "", a).strip()
    return " and ".join(x.strip() for x in a.split(",") if x.strip())


def kind(venue: str) -> str:
    v = venue.lower()
    if "arxiv" in v:
        return "misc"
    if any(w in v for w in ("journal", "review", "letters", "communications", "quantum technology", "synthesis",
                            "j. appl", "artificial intelligence", "sttt", "international")):
        return "article"
    return "inproceedings"


def main():
    d = json.loads(SRC.read_text(encoding="utf-8"))
    ver = {r["key"]: r for r in d["vrefs"]["results"]}
    out = ["% Generated by paper/scripts/make_bib.py from the verified literature sweep. Do not edit by hand.\n"]
    for r in d["refs"]["references"]:
        v = ver.get(r["key"], {})
        if not v.get("exists"):
            print("dropped (not verified):", r["key"])
            continue
        r = {**r, **{k: val for k, val in (v.get("corrected") or {}).items() if val}}
        key = RENAME.get(r["key"], r["key"])
        k = kind(r["venue"])
        fields = {"author": authors_bib(r["authors"]), "title": "{" + r["title"] + "}", "year": str(r["year"])}
        if k == "article":
            fields["journal"] = r["venue"]
        elif k == "inproceedings":
            fields["booktitle"] = r["venue"]
        else:
            fields["howpublished"] = r["venue"]
        if r.get("doi"):
            fields["doi"] = r["doi"]
        if r.get("url"):
            fields["url"] = r["url"]
        body = ",\n".join(f"  {f} = {{{esc(val) if f not in ('url', 'doi') else val}}}" for f, val in fields.items())
        out.append(f"@{k}{{{key},\n{body}\n}}\n")
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT} ({len(out) - 1} entries)")


if __name__ == "__main__":
    sys.exit(main())
