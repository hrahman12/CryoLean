#!/usr/bin/env python
"""Write paper/FIGURE_INDEX.md from the metadata every figure script saves (paper/figures/meta/*.json)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
META = ROOT / "paper" / "figures" / "meta"
OUT = ROOT / "paper" / "FIGURE_INDEX.md"
ORDER_FILE = ROOT / "paper" / "data" / "figure_order.json"   # optional: {"main": [...], "supplement": [...]}


def main():
    metas = {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in sorted(META.glob("*.json"))}
    order = json.loads(ORDER_FILE.read_text(encoding="utf-8")) if ORDER_FILE.exists() else {}
    main_ids = [n for n in order.get("main", []) if n in metas]
    sup_ids = [n for n in order.get("supplement", []) if n in metas]
    rest = [n for n in metas if n not in main_ids + sup_ids]
    main_ids += [n for n in rest if metas[n].get("section") == "main"]
    sup_ids += [n for n in rest if metas[n].get("section") != "main"]
    lines = ["# Figure index", "",
             "Every figure in the paper and the README is generated by a script in `paper/scripts/` from data in `paper/data/`, "
             "from real runs of the Lean checker and Z3, or from sourced catalog data. This file is generated by "
             "`python paper/scripts/build_figure_index.py` from the metadata each script saves.", "",
             "Claim classes: **PROVEN** machine-checked by Lean · **COMPUTED** produced by running CryoLean · **MEASURED** "
             "timing on this machine · **MODELED** from a documented physical model with stated assumptions · **SOURCED** "
             "from manufacturer documentation or literature · **ILLUSTRATIVE** a schematic, not data.", "",
             "| # | Figure | Claim | Section | Files |", "|---|---|---|---|---|"]
    numbered = [(f"F{i}", n) for i, n in enumerate(main_ids, 1)] + [(f"S{i}", n) for i, n in enumerate(sup_ids, 1)]
    for num, n in numbered:
        m = metas[n]
        files = f"[png](figures/{n}.png) · [svg](figures/{n}.svg) · [pdf](figures/{n}.pdf)"
        if m.get("interactive"):
            files += f" · [interactive]({m['interactive'].replace('paper/', '')})"
        lines.append(f"| {num} | [{m['title']}](#{n.replace('_', '-')}) | {m['claim']} | {'main' if num.startswith('F') else 'supplement'} | {files} |")
    lines.append("")
    for num, n in numbered:
        m = metas[n]
        lines += [f"## {n}", "", f"**{num}. {m['title']}**", "", f"![{m['title']}](figures/{n}.png)", "",
                  f"- **Research question.** {m['question']}",
                  f"- **Model or method.** {m['model']}",
                  f"- **Data provenance.** {m['data']}",
                  f"- **Claim class.** {m['claim']}",
                  f"- **Caption.** {m['caption']}",
                  f"- **Reproduce.** `{m['command']}`" + (f" (interactive: `{m['interactive']}`)" if m.get("interactive") else ""),
                  ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(numbered)} figures)")


if __name__ == "__main__":
    main()
