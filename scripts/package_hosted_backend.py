"""Package the real Python + Linux Lean backend with Vercel Build Output API v3.

Run build_linux_backend.sh in Linux/WSL first. Only reviewed seeds, application
code and runtime dependencies are shipped, never a local DB or credentials.
"""
from __future__ import annotations
import hashlib
import gzip
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FUNC = ROOT / ".vercel/output/functions/api/bridge.func"


def main():
    FUNC.mkdir(parents=True, exist_ok=True)
    linux = ROOT / ".tools/linux-backend/cryolean"
    if not linux.exists(): raise SystemExit("Build the Linux Lean checker first")
    if linux.read_bytes()[:4] != b'\x7fELF': raise SystemExit("Hosted checker must be a Linux ELF executable")
    for directory in ("cryolean", "data", "api"):
        shutil.copytree(ROOT / directory, FUNC / directory, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "*.db", "*.db-*", "registry", "candidates", "research_requests"))
    for directory in ("research/expansion", "research/v4/scene"):
        shutil.copytree(ROOT / directory, FUNC / directory, dirs_exist_ok=True, ignore=shutil.ignore_patterns("*.py", "*.md", "__pycache__"))
    shutil.copy2(ROOT / "research/v4/site_selection.json", FUNC / "research/v4/site_selection.json")
    (FUNC / "lean/bin").mkdir(parents=True, exist_ok=True)
    (FUNC / "lean/CryoLean").mkdir(parents=True, exist_ok=True)
    binary=linux.read_bytes()
    (FUNC / 'lean/bin/cryolean.gz').write_bytes(gzip.compress(binary,compresslevel=9,mtime=0))
    (FUNC / 'lean/bin/cryolean.sha256').write_text(hashlib.sha256(binary).hexdigest())
    # Remove the earlier unpacked build artifact; Vercel limits individual uploads to 100 MB.
    old=FUNC / 'lean/bin/cryolean'
    if old.exists():old.unlink()
    for p in (ROOT / "lean").glob("*.lean"): shutil.copy2(p, FUNC / "lean" / p.name)
    for p in (ROOT / "lean/CryoLean").glob("*.lean"): shutil.copy2(p, FUNC / "lean/CryoLean" / p.name)
    audit = ROOT / ".tools/linux-backend/audit-axioms.json"
    if not audit.exists(): raise SystemExit("Generate the actual Linux theorem audit first")
    shutil.copy2(audit, FUNC / "lean/audit-axioms.json")
    vendor = FUNC / "_vendor"
    if not (vendor / "vercel_runtime").is_dir():
        subprocess.run([sys.executable,"-m","pip","install","--target",str(vendor),"--only-binary=:all:",
                        "--platform","manylinux2014_x86_64","--implementation","cp","--python-version","3.12",
                        "fastapi==0.121.3","z3-solver==4.15.4.0","vercel-runtime==0.24.1"],check=True)
    # Same runtime trampoline generated by @vercel/python (official builder).
    (FUNC / "vc__handler__python.py").write_text('''import os, sys, site
from pathlib import Path
root = Path(__file__).resolve().parent
site.addsitedir(str(root / "_vendor"))
sys.path.insert(0,str(root))
os.environ.update({"__VC_HANDLER_MODULE_NAME":"api.index","__VC_HANDLER_ENTRYPOINT":"api/index.py",
"__VC_HANDLER_ENTRYPOINT_ABS":str(root/"api/index.py"),"__VC_HANDLER_VENDOR_DIR":"_vendor",
"__VC_HANDLER_VARIABLE_NAME":"app"})
from vercel_runtime.vc_init import vc_handler
''',encoding="utf-8")
    (FUNC / ".vc-config.json").write_text(json.dumps({"runtime":"python3.12","handler":"vc__handler__python.vc_handler",
        "maxDuration":60,"memory":2048,"environment":{"PYTHONPATH":"_vendor","PYTHONDONTWRITEBYTECODE":"1",
        "CRYOLEAN_AI_PROVIDER":"lexical","CRYOLEAN_LEAN_TIMEOUT":"45"}}),encoding="utf-8")
    print("Packaged real backend:", round(sum(p.stat().st_size for p in FUNC.rglob('*') if p.is_file())/1048576,1), "MiB")

if __name__ == '__main__': main()
