#!/usr/bin/env python
"""Compile data/evidence/*.json fragments into the single data/evidence.json provenance database,
and regenerate RESEARCH_SOURCES.md (source inventory grouped by document)."""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"


def main() -> int:
    records = []
    seen = set()
    for p in sorted((DATA / "evidence").glob("*.json")):
        for rec in json.loads(p.read_text(encoding="utf-8")):
            if rec["id"] in seen:
                print(f"duplicate evidence id {rec['id']} in {p.name}", file=sys.stderr)
                return 1
            seen.add(rec["id"])
            rec["_fragment"] = p.name
            records.append(rec)
    out = [{k: v for k, v in r.items() if k != "_fragment"} for r in records]
    (DATA / "evidence.json").write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote data/evidence.json with {len(out)} records")

    # ---- RESEARCH_SOURCES.md
    by_doc: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for r in records:
        by_doc[(r.get("document_title") or "(untitled)", r.get("source_url") or "")].append(r)
    status_counts = defaultdict(int)
    for r in records:
        status_counts[r.get("evidence_status")] += 1

    lines = ["# RESEARCH_SOURCES — source inventory and citations", "",
             "Generated by `scripts/build_evidence.py` from `data/evidence/*.json`. Every value in the trusted catalog",
             "points at one of the records below; each record stores the verbatim quote, document title, page/section,",
             "configuration applicability, evidence status and access date.", "",
             f"* evidence records: **{len(records)}**",
             f"* distinct documents: **{len(by_doc)}**",
             "* by status: " + ", ".join(f"{k}: {v}" for k, v in sorted(status_counts.items())), "",
             "Research notes (raw, with every fetched and failed URL) live in `research/*.md`.", "",
             "Evidence statuses: `manufacturer_specification` (datasheet/manual), `experimental_observation` (peer-reviewed",
             "paper or published protocol), `user_entered`, `inferred_estimate` (never trusted by the checker), `unknown`.", "",
             "## Documents", ""]
    frag_order = defaultdict(list)
    for (title, url), recs in sorted(by_doc.items(), key=lambda kv: (kv[1][0]["_fragment"], kv[0][0])):
        frag_order[recs[0]["_fragment"]].append((title, url, recs))
    for frag, docs in frag_order.items():
        lines.append(f"### {frag.replace('.json', '').replace('_', ' ').title()}")
        lines.append("")
        for title, url, recs in docs:
            ids = ", ".join(r["id"] for r in recs)
            acc = sorted({r.get("accessed", "") for r in recs})
            doi = sorted({r.get("doi") for r in recs if r.get("doi")})
            lines.append(f"- **{title}**  ")
            lines.append(f"  {url}  ")
            if doi:
                lines.append(f"  DOI: {', '.join(doi)}  ")
            lines.append(f"  accessed {', '.join(acc)} · {len(recs)} record(s): {ids}")
        lines.append("")
    lines += ["## Known gaps", "",
              "Records with `evidence_status: unknown` mark capabilities the sources did not state; they are listed per",
              "configuration in `GET /coverage` → `missing_scientific_data`. The catalog is not complete: only the",
              "equipment and experiments listed in `data/` have been researched.", ""]
    (ROOT / "RESEARCH_SOURCES.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote RESEARCH_SOURCES.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
